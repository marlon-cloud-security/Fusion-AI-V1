def initialize_memory():
    """Inicializa la memoria para una nueva ejecución."""

    os.makedirs(os.path.dirname(MEMORY_FILE), exist_ok=True)

    with memory_lock:
        with open(MEMORY_FILE, "w", encoding="utf-8") as file:
            json.dump([], file, indent=4)
def load_memory():
    """
    FUSION-AI // Unified Runtime Memory Aggregator

    Priority:
      1. outputs/json/report.json   (Nmap + SearchSploit enriched cards)
      2. outputs/report.json        (live mirror)
      3. outputs/fusion_history.json (stream generated by remaining modules)

    Cards are merged by ID so the richest version always survives.
    """

    report_sources = [
        os.path.join(BASE_DIR, "outputs", "json", "report.json"),
        os.path.join(BASE_DIR, "outputs", "report.json")
    ]

    merged = {}

    def merge_card(card):
        card_id = str(card.get("id", "")).strip()

        # 🔒 EL CANDADO EXCLUSIVO PARA NMAP:
        # Si el hallazgo es de nmap y trae puerto, forzamos un ID único universal 
        # para que tu lógica de-duplique de forma perfecta sin importar el historial.
        if str(card.get("module", "")).lower() == "nmap" and card.get("port") is not None:
            card_id = f"home-live-{card.get('port')}"

        if not card_id:
            card_id = f"{card.get('module','unknown')}::{card.get('title','unknown')}"

        existing = merged.get(card_id)

        if existing is None:
            merged[card_id] = card
            return

        old_score = 0
        new_score = 0

        sev_rank = {
            "critical":4,
            "high":3,
            "medium":2,
            "low":1
        }

        old_score += sev_rank.get(str(existing.get("severity","")).lower(),0)
        new_score += sev_rank.get(str(card.get("severity","")).lower(),0)

        old_score += len(existing.get("data",{}))
        new_score += len(card.get("data",{}))

        if existing.get("data",{}).get("exploit_available"):
            old_score += 10

        if card.get("data",{}).get("exploit_available"):
            new_score += 10

        if new_score > old_score:
            existing.update(card)

            if "data" in card:
                existing.setdefault("data",{})
                existing["data"].update(card["data"])

            merged[card_id] = existing

    with memory_lock:

        # ---------- Read Nmap reports first ----------
        for path in report_sources:

            try:

                if not os.path.exists(path):
                    continue

                with open(path,"r",encoding="utf-8") as f:
                    data=json.load(f)

                if isinstance(data,dict):
                    for card in data.get("findings",[]):
                        merge_card(card)

                elif isinstance(data,list):
                    for card in data:
                        merge_card(card)

            except Exception:
                continue

        # ---------- Merge live module stream ----------
        try:

            if os.path.exists(MEMORY_FILE):

                with open(MEMORY_FILE,"r",encoding="utf-8") as f:
                    history=json.load(f)

                if isinstance(history,list):
                    for card in history:
                        merge_card(card)

        except Exception:
            pass

    findings=list(merged.values())
    findings=[f for f in findings if f]

    severity_order={
        "critical":4,
        "high":3,
        "medium":2,
        "low":1
    }

    findings.sort(
        key=lambda x: severity_order.get(
            str(x.get("severity","")).lower(),0
        ),
        reverse=True
    )

    return findings
def save_memory(data):
    with memory_lock:
        with open(MEMORY_FILE, "w", encoding="utf-8") as file:
            json.dump(data, file, indent=4, ensure_ascii=False)

